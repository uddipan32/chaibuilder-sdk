// Vendors Tailwind CSS v4's stylesheets into a generated TypeScript module so page-styles
// compilation never touches the filesystem at runtime. Filesystem resolution of these files is
// unreliable across package managers (npm/pnpm/bun layouts) and serverless bundlers (file tracing
// cannot see fs.readFile with computed paths).
//
// Run after bumping the tailwindcss dependency: node scripts/vendor-tailwind-v4-css.mjs
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(scriptDir, "..");
const require = createRequire(path.join(packageRoot, "package.json"));

const tailwindRoot = path.dirname(require.resolve("tailwindcss/package.json"));
const { version } = JSON.parse(readFileSync(path.join(tailwindRoot, "package.json"), "utf8"));

if (!version.startsWith("4.")) {
  throw new Error(`Expected tailwindcss v4 to vendor from, resolved ${version}.`);
}

const FILES = ["index.css", "theme.css", "preflight.css", "utilities.css"];
const stylesheets = Object.fromEntries(
  FILES.map((file) => [file, readFileSync(path.join(tailwindRoot, file), "utf8")]),
);

const output = `// AUTO-GENERATED by scripts/vendor-tailwind-v4-css.mjs — do not edit by hand.
// Regenerate after bumping the tailwindcss dependency: node scripts/vendor-tailwind-v4-css.mjs
//
// Tailwind v4's stylesheets are vendored so page-styles compilation needs no filesystem access at
// runtime — resolving these files from node_modules is unreliable across package managers and
// serverless bundlers.
export const VENDORED_TAILWIND_V4_VERSION = ${JSON.stringify(version)};

export const TAILWIND_V4_STYLESHEETS: Record<string, string> = {
${FILES.map((file) => `  ${JSON.stringify(file)}: ${JSON.stringify(stylesheets[file])},`).join("\n")}
};
`;

const outFile = path.join(packageRoot, "src", "utils", "tailwind-v4-stylesheets.generated.ts");
writeFileSync(outFile, output);
console.log(`Vendored tailwindcss@${version} stylesheets to ${path.relative(packageRoot, outFile)}`);
